"""DVF raw rows -> one row per residential sale.
Step 1: csv.gz -> Parquet, all columns as strings (DuckDB, streaming).
Step 2: rebuild sales and apply filters (Polars); prints lineage counts."""

from pathlib import Path
import duckdb
import polars as pl

RAW = Path("data/raw/dvf")
BRONZE = Path("data/interim/dvf_raw")
OUT = Path("data/interim/dvf_sales.parquet")
LOGEMENT = ["Maison", "Appartement"]


def to_parquet() -> None:
    """
    Convert raw DVF CSV files to Parquet format, storing all columns as strings.
    This function reads each CSV file in the RAW directory, converts it to Parquet format using DuckDB, and saves the resulting Parquet files in the BRONZE directory. 
    If a Parquet file already exists for a given CSV file, it will be skipped to avoid redundant processing.
    The Parquet files are compressed using Zstandard (zstd) compression for efficient storage.
    """
    BRONZE.mkdir(parents=True, exist_ok=True)
    for f in sorted(RAW.glob("dvf_*.csv.gz")):
        target = BRONZE / f.name.replace(".csv.gz", ".parquet")
        if target.exists():
            print(f"skip {target}")
            continue
        duckdb.execute(
            f"COPY (SELECT * FROM read_csv('{f.as_posix()}', all_varchar=true, header=true, "
            f"delim=',', quote='\"', escape='\"')) "
            f"TO '{target.as_posix()}' (FORMAT parquet, COMPRESSION zstd)"
        )
        print(f"{f.name} -> {target.name}")


def num(c: str) -> pl.Expr:
    """
    Convert a column to float64, handling null values.
    """
    return pl.col(c).cast(pl.Float64, strict=False)


def first_log(c: str) -> pl.Expr:
    """
    Get the value of column c for the first dwelling row in a sale.
    """
    return pl.col(c).filter(pl.col("is_log")).first()


def clean() -> None:
    """
    Clean and filter DVF sales data, producing a Parquet file with one row per residential sale.
    This function reads the Parquet files generated by the to_parquet function, filters the data to include only residential sales, and applies various cleaning steps. 
    The resulting cleaned data is saved as a Parquet file in the OUT directory.
    The function also prints lineage counts for each filtering step, providing insight into how many rows remain after each filter is applied.
    """

    lineage: list[tuple[str, int]] = []

    lf = (
        pl.scan_parquet(BRONZE / "*.parquet")
        .filter(pl.col("nature_mutation") == "Vente")
        .with_columns(
            valeur=num("valeur_fonciere"),
            surf_bati=num("surface_reelle_bati"),
            pieces=num("nombre_pieces_principales"),
            carrez=num("lot1_surface_carrez"),
            terrain=num("surface_terrain"),
            lon=num("longitude"),
            lat=num("latitude"),
            date=pl.col("date_mutation").str.to_date(),
            is_log=pl.col("type_local").is_in(LOGEMENT),
        )
    )

    # the same dwelling can appear on several rows (one per parcel): identify it by its attributes
    log_key = pl.concat_str(
        ["type_local", "surface_reelle_bati", "nombre_pieces_principales", "lot1_numero"],
        separator="|", ignore_nulls=True,
    )

    # land area: count each parcel once per sale
    terrain = (
        lf.filter(pl.col("terrain").is_not_null())
        .unique(["id_mutation", "id_parcelle", "nature_culture", "surface_terrain"])
        .group_by("id_mutation")
        .agg(surface_terrain=pl.col("terrain").sum())
    )

    sales = (
        lf.group_by("id_mutation")
        .agg(
            date=pl.col("date").first(),
            valeur=pl.col("valeur").first(),
            n_valeurs=pl.col("valeur").n_unique(),
            n_logements=log_key.filter(pl.col("is_log")).n_unique(),
            n_dependances=(pl.col("type_local") == "Dépendance").sum(),
            n_locaux_pro=pl.col("type_local").str.starts_with("Local").sum(),
            type_bien=first_log("type_local"),
            surface_bati=first_log("surf_bati"),
            pieces=first_log("pieces"),
            surface_carrez=first_log("carrez"),
            adresse_numero=first_log("adresse_numero"),
            adresse_suffixe=first_log("adresse_suffixe"),
            adresse_nom_voie=first_log("adresse_nom_voie"),
            code_postal=first_log("code_postal"),
            code_commune=first_log("code_commune"),
            nom_commune=first_log("nom_commune"),
            code_departement=first_log("code_departement"),
            id_parcelle=first_log("id_parcelle"),
            lon=first_log("lon"),
            lat=first_log("lat"),
        )
        .join(terrain, on="id_mutation", how="left")
        .with_columns(pl.col("surface_terrain").fill_null(0))
        .collect(engine="streaming")
    )
    lineage.append(("sales (Vente, all types)", sales.height))

    steps = [
        ("contains a dwelling", pl.col("n_logements") >= 1),
        ("exactly one dwelling", pl.col("n_logements") == 1),
        ("no commercial premises", pl.col("n_locaux_pro") == 0),
        ("single consistent price", pl.col("n_valeurs") == 1),
        ("price 15k-10M EUR", pl.col("valeur").is_between(15_000, 10_000_000)),
        ("surface 9-1000 m2", pl.col("surface_bati").is_between(9, 1000)),
    ]
    for name, cond in steps:
        sales = sales.filter(cond)
        lineage.append((name, sales.height))

    # price per m2 outliers: trim 1% each side within département x type
    sales = sales.with_columns(prix_m2=pl.col("valeur") / pl.col("surface_bati"))
    lo = pl.col("prix_m2").quantile(0.01).over(["code_departement", "type_bien"])
    hi = pl.col("prix_m2").quantile(0.99).over(["code_departement", "type_bien"])
    sales = sales.filter(pl.col("prix_m2").is_between(lo, hi))
    lineage.append(("price/m2 within dept x type P1-P99", sales.height))

    sales = sales.drop("n_valeurs", "n_logements", "n_locaux_pro")
    sales.write_parquet(OUT, compression="zstd")

    print("\nLineage")
    for name, n in lineage:
        print(f"  {name:38} {n:>10,}")
    print(f"\nwritten {OUT}")
    print(sales.group_by("type_bien", pl.col("date").dt.year().alias("year"))
               .agg(n=pl.len(), median_prix_m2=pl.col("prix_m2").median().round(0))
               .sort("type_bien", "year"))


if __name__ == "__main__":
    to_parquet()
    clean()